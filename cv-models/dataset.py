import os
import cv2 as cv
import numpy as np
import torch
from torch.utils.data import Dataset

class OilSpillDataset(Dataset):
    def __init__(self, image_dir, mask_dir, transform=None):
        self.image_dir = image_dir
        self.mask_dir = mask_dir
        self.transform = transform
        
        # Load only valid image extensions
        valid_ext = ('.jpg', '.png', '.jpeg', '.tif')
        self.images = sorted([f for f in os.listdir(image_dir) if f.lower().endswith(valid_ext)])

    def __len__(self):
        return len(self.images)

    def __getitem__(self, index):
        file_name = self.images[index]
        image_path = os.path.join(self.image_dir, file_name)
        
        # Binary masks generated by Otsu script will share the same filename
        mask_path = os.path.join(self.mask_dir, file_name)

        # 1. Load Image (Grayscale) and Mask (Grayscale)
        image = cv.imread(image_path, cv.IMREAD_GRAYSCALE)
        mask = cv.imread(mask_path, cv.IMREAD_GRAYSCALE)

        if image is None or mask is None:
            raise ValueError(f"Missing image or mask data for: {file_name}")

        # 2. Normalization
        # SAR images often have high pixel intensities; normalize to [0, 1]
        image = image.astype(np.float32) / 255.0
        
        # Convert pixel values (0 or 255) to exact binary float (0.0 or 1.0)
        mask = (mask > 127).astype(np.float32)

        # 3. Apply Albumentations (Resizing + Augmentation)
        if self.transform:
            augmented = self.transform(image=image, mask=mask)
            image = augmented['image']
            mask = augmented['mask']
        else:
            # Fallback tensor conversion if no transforms are passed
            image = torch.tensor(image, dtype=torch.float32).unsqueeze(0)
            mask = torch.tensor(mask, dtype=torch.float32).unsqueeze(0)

        return image, mask